function tc(
  id,
  phase,
  feature,
  scenario,
  description,
  steps,
  expected,
  priority,
  type,
  severity = "Medium",
  preconditions = PRE,
  testData = "",
) {
  return {
    id: `IND-AOB-${String(id).padStart(4, "0")}`,
    module: MODULE,
    feature: `${phase} > ${feature}`,
    requirementId: `REQ-AOB-${String(id).padStart(4, "0")}`,
    scenario,
    description,
    preconditions,
    testData,
    steps,
    expected,
    priority,
    severity,
    type,
    status: "Not Executed",
  };
}

